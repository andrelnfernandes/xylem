//! Build script:
//! - Discovers translated manual topics in `docs/manual/<lang>/*.md` so new
//!   topics and languages added by contributors are embedded automatically
//!   without editing Rust code.
//! - Lists the layouts of `layouts/**/*.xlayout.toml` to build them in, so
//!   that a layout contributed to the catalog needs no Rust either.
//! - On Windows, embeds the icon (`docs/icons/xylem.ico`) and version
//!   information in `xy.exe`.

use std::env;
use std::fs;
use std::path::PathBuf;

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=docs/icons/xylem.ico");
    println!("cargo:rerun-if-changed=docs/manual");
    println!("cargo:rerun-if-changed=layouts");

    generate_manual_translations();
    generate_layout_catalog();

    // Building on Windows for Windows, as the CI and the releases do.
    #[cfg(windows)]
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("windows") {
        let mut res = winresource::WindowsResource::new();
        res.set_icon("docs/icons/xylem.ico");
        res.compile().expect("cannot embed the icon in xy.exe");
    }
}

/// `CATALOG`: each layout file by its path under `layouts/`, in order.
fn generate_layout_catalog() {
    fn walk(dir: &std::path::Path, out: &mut Vec<PathBuf>) {
        let Ok(entries) = fs::read_dir(dir) else {
            return;
        };
        for entry in entries.flatten() {
            let path = entry.path();
            if path.is_dir() {
                println!("cargo:rerun-if-changed={}", path.display());
                walk(&path, out);
            } else if path
                .file_name()
                .and_then(|n| n.to_str())
                .is_some_and(|n| n.ends_with(".xlayout.toml"))
            {
                println!("cargo:rerun-if-changed={}", path.display());
                out.push(path);
            }
        }
    }
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let root = manifest_dir.join("layouts");
    let mut files = Vec::new();
    walk(&root, &mut files);
    files.sort();
    let mut code = String::from(
        "// Generated by build.rs from layouts/**/*.xlayout.toml\n\
         pub const CATALOG: &[(&str, &str)] = &[\n",
    );
    for path in files {
        let rel = path
            .strip_prefix(&root)
            .unwrap()
            .to_string_lossy()
            .replace('\\', "/");
        let path_str = path.to_string_lossy().replace('\\', "/");
        code.push_str(&format!("    ({rel:?}, include_str!({path_str:?})),\n"));
    }
    code.push_str("];\n");
    let dest = PathBuf::from(env::var("OUT_DIR").unwrap()).join("layout_catalog.rs");
    fs::write(dest, code).expect("cannot write layout_catalog.rs");
}

fn generate_manual_translations() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let manual_dir = manifest_dir.join("docs").join("manual");
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    let dest = out_dir.join("manual_translations.rs");

    let mut langs: Vec<(String, Vec<(String, PathBuf)>)> = Vec::new();
    if let Ok(entries) = fs::read_dir(&manual_dir) {
        let mut dirs: Vec<PathBuf> = entries
            .flatten()
            .map(|e| e.path())
            .filter(|p| p.is_dir())
            .collect();
        dirs.sort();
        for dir in dirs {
            let Some(lang) = dir.file_name().and_then(|s| s.to_str()) else {
                continue;
            };
            if lang.starts_with('.') {
                continue;
            }
            println!("cargo:rerun-if-changed={}", dir.display());
            let mut topics: Vec<(String, PathBuf)> = Vec::new();
            if let Ok(files) = fs::read_dir(&dir) {
                for file in files.flatten() {
                    let path = file.path();
                    if path.extension().and_then(|e| e.to_str()) != Some("md") {
                        continue;
                    }
                    let Some(stem) = path.file_stem().and_then(|s| s.to_str()) else {
                        continue;
                    };
                    if matches!(stem, "README" | "TRANSLATING") {
                        continue;
                    }
                    println!("cargo:rerun-if-changed={}", path.display());
                    topics.push((stem.to_string(), path));
                }
            }
            topics.sort_by(|a, b| a.0.cmp(&b.0));
            if !topics.is_empty() {
                langs.push((lang.to_string(), topics));
            }
        }
    }

    let mut code = String::from(
        "// Generated by build.rs from docs/manual/<lang>/*.md\n\
         pub const EMBEDDED_TRANSLATIONS: &[(&str, &[(&str, &str)])] = &[\n",
    );
    for (lang, topics) in langs {
        code.push_str(&format!("    ({lang:?}, &[\n"));
        for (name, path) in topics {
            let path_str = path.to_string_lossy().replace('\\', "/");
            code.push_str(&format!(
                "        ({name:?}, include_str!({path_str:?})),\n"
            ));
        }
        code.push_str("    ]),\n");
    }
    code.push_str("];\n");
    fs::write(dest, code).expect("cannot write manual_translations.rs");
}
